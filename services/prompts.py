def example_answer(feeling, rewrite):
    """示例里助手的回答：和要求模型输出的 JSON 格式完全一样。"""
    return json.dumps({"speaker_feeling": feeling, "rewrite": rewrite}, ensure_ascii=False)


def soften_user_message(original, lang=None):
    """把原话包成发给模型的那条消息。lang 是代码判断出的原话语言（"zh" / "en" / None），
    写明了输出语言，模型就不会把中文改成英文。"""
    target = {"zh": "\nrewrite 的语言：中文", "en": "\nrewrite language: English"}.get(lang, "")
    return f"<原话>{original}</原话>{target}"


