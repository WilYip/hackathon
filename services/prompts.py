# 示例：(原话, 改写)。会作为几轮对话放在真正的原话前面，教模型保持"说话人 → 伴侣"的人称和原话的语言。
SOFTEN_EXAMPLES = [
    ("你是头猪", "我现在真的很生气，气到想骂人。我们能不能先停一下，好好聊聊刚才的事？"),
    ("你又不回我消息，你根本不在乎我", "你一直没回我消息，我有点不安，我希望能感受到你在乎我。"),
    ("气死我了，你怎么又迟到", "你又迟到了，我真的有点生气。下次能不能早点出门，或者提前跟我说一声？"),
    ("你在干嘛", "你在干嘛呀？"),
    ("随便", "我都可以，你来定吧～"),
    ("You never listen to me.", "I feel unheard sometimes, and I'd really like you to listen to me."),
]


def soften_user_message(original, lang=None):
    """把原话包成发给模型的那条消息。lang 是代码判断出的原话语言（"zh" / "en" / None），
    写明了输出语言，模型就不会把中文改成英文。"""
    target = {"zh": "\n输出语言：中文", "en": "\nOutput language: English"}.get(lang, "")
    return f"<原话>{original}</原话>{target}"


